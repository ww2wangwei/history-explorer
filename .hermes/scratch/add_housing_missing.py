def mk_entry(tid, facts_list, sections_list, timeline_list, images_list, related_list, source_str):
    return {
        'facts': [{'label': k, 'value': v} for k, v in facts_list],
        'sections': sections_list,
        'timeline': [{'year': y, 'era': e, 'event': ev} for y, e, ev in timeline_list],
        'images': [{'imageKeyword': i, 'caption': c, 'credit': cr} for i, c, cr in images_list],
        'related': [{'id': rid, 'title': rt, 'reason': rr} for rid, rt, rr in related_list],
        'source': source_str,
    }

def P(h, b): return {'type': 'paragraph', 'heading': h, 'body': b}
def C(h, b, variant='info'): return {'type': 'callout', 'heading': h, 'body': b, 'variant': variant}
def L(h, items): return {'type': 'list', 'heading': h, 'items': items}
def Q(text, cite): return {'type': 'quote', 'text': text, 'cite': cite}

