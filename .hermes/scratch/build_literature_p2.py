# --- Builders ---
def f(label, value):
    return {"label": label, "value": value}

def para(heading, body):
    return {"type": "paragraph", "heading": heading, "body": body}

def callout(heading, body, variant="info"):
    return {"type": "callout", "heading": heading, "body": body, "variant": variant}

def lst(heading, items):
    return {"type": "list", "heading": heading, "items": items}

def quote(text, cite=None):
    q = {"type": "quote", "text": text}
    if cite: q["cite"] = cite
    return q

def tl(year, event, era=None):
    e = {"year": year, "event": event}
    if era: e["era"] = era
    return e

def img(imageKeyword, caption, credit="Wikimedia Commons · Public Domain"):
    return {"imageKeyword": imageKeyword, "caption": caption, "credit": credit}

def rel(rid, title, reason):
    return {"id": rid, "title": title, "reason": reason}


