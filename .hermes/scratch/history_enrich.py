    def find_item_span(text: str, tid: str) -> tuple[int, int] | None:
        """找到 { id: 'tid', category: 'history', ... } 的精确 span（花括号配对，处理嵌套）。"""
        anchor = f"{{ id: '{tid}', category: 'history'"
        idx = text.find(anchor)
        if idx < 0:
            return None
        start = idx
        depth = 0
        i = start
        while i < len(text):
            ch = text[i]
            if ch == '{':
                depth += 1
            elif ch == '}':
                depth -= 1
                if depth == 0:
                    return (start, i + 1)
            i += 1
        return None

    def find_full_content_end(text: str, item_start: int, item_end: int) -> int | None:
        """在条目范围内找到 fullContent: '...' 字符串的结束引号位置。"""
        fc_idx = text.find("fullContent:", item_start, item_end)
        if fc_idx < 0:
            return None
        q1 = text.find("'", fc_idx)
        if q1 < 0 or q1 >= item_end:
            return None
        i = q1 + 1
        while i < item_end:
            ch = text[i]
            if ch == '\\' and i + 1 < item_end:
                i += 2
                continue
            if ch == "'":
                return i
            i += 1
        return None

