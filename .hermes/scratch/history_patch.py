# 紧凑 entry 工厂
def E(id_, cat, title, summary, era, ik, fc, figure, facts, sections, timeline, images, related, source):
    f_field = f", figure: '{figure}'" if figure else ''
    lines = []
    lines.append(f"  {{ id: '{id_}', category: '{cat}', title: '{title}', summary: '{summary}', era: '{era}'{f_field}, imageKeyword: '{ik}', fullContent: '{fc}',")
    lines.append("    facts: [")
    for fl, fv in facts: lines.append(f"      {{ label: '{fl}', value: '{fv}' }},")
    lines.append("    ],")
    lines.append("    sections: [")
    for s in sections: lines.append("      " + s.replace(chr(10), chr(10)+'      ') + ",")
    lines.append("    ],")
    lines.append("    timeline: [")
    for y, er, ev in timeline: lines.append(f"      {{ year: '{y}', era: '{er}', event: '{ev}' }},")
    lines.append("    ],")
    lines.append("    images: [")
    for ik2, cap, cr in images: lines.append(f"      {{ imageKeyword: '{ik2}', caption: '{cap}', credit: '{cr}' }},")
    lines.append("    ],")
    lines.append("    related: [")
    for rid, rt, re_ in related: lines.append(f"      {{ id: '{rid}', title: '{rt}', reason: '{re_}' }},")
    lines.append("    ],")
    lines.append(f"    source: '{source}',")
    lines.append("  },")
    return chr(10).join(lines)

