def main():
    text = FILE.read_text(encoding='utf-8')
    array_start = text.find('export const TRADITIONS')

    ok, fail = [], []
    for eid, args in E_.items():
        # find old single-line entry
        sig = f"id: '{eid}'"
        idx = text.find(sig, array_start)
        if idx < 0:
            fail.append((eid, 'NOT FOUND'))
            continue
        # left char must be {
        start = text.rfind('{', array_start, idx)
        # find },  after start
        end = text.find('},', start) + 2
        old = text[start:end]
        if text.count(old) != 1:
            fail.append((eid, f'appears {text.count(old)} times'))
            continue
        new = args  # already the formatted entry
        text = text.replace(old, new, 1)
        ok.append(eid)

    FILE.write_text(text, encoding='utf-8')
    print(f'OK: {len(ok)}, FAIL: {len(fail)}')
    for f in fail:
        print(' FAIL:', f)
    if not fail:
        print('All entries applied.')

if __name__ == '__main__':
    main()
