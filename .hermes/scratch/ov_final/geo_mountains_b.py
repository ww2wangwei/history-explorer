def C(heading, body, variant='info'): return {'type': 'callout', 'heading': heading, 'body': body, 'variant': variant}
def L(heading, items): return {'type': 'list', 'heading': heading, 'items': items}
def Q(text, cite): return {'type': 'quote', 'text': text, 'cite': cite}
def T(year, event, era=None):
    out = {'year': year, 'event': event}
    if era: out['era'] = era
    return out
def I(kw, cap, credit='Wikimedia Commons'): return {'imageKeyword': kw, 'caption': cap, 'credit': credit}
def R(rid, title, reason): return {'id': rid, 'title': title, 'reason': reason}

def add(eid, data): enrich[eid] = data

