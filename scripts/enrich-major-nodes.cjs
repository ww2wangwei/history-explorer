// 在 MAJOR_WARS 中找对应节点更新
// 策略：在 MAJOR_WARS 数组中按 majorKey 找、然后按 title 找 node、然后用 4 段属性替换
// 由于整个文件太大，我们用直接字符串替换：找 { title: 'xxx', year: yyy, location: '...', description: '...', importance: n }

let updated = 0;
const notFound = [];

NODE_ENRICHMENTS.forEach(en => {
  // 转义正则特殊字符
  const escapeReg = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  // 匹配: { title: 'xxx', year: yyy, location: '...', description: '...', importance: n }
  // 注意 description 可能跨多行没
  const titleEsc = escapeReg(en.title);
  const re = new RegExp(
    "(\\{\\s*title:\\s*'" + titleEsc + "',\\s*year:\\s*-?\\d+,\\s*location:\\s*'[^']*',\\s*importance:\\s*\\d+,\\s*description:\\s*)'([^']*)'(\\s*\\})",
  );
  if (!re.test(s)) {
    notFound.push(en.title);
    return;
  }
  s = s.replace(re, (match, prefix, oldDesc, suffix) => {
    return prefix + "'" + oldDesc + "'," +
      `\n        background: ${JSON.stringify(en.background)},` +
      `\n        detail: ${JSON.stringify(en.detail)},` +
      `\n        result: ${JSON.stringify(en.result)},` +
      `\n        impact: ${JSON.stringify(en.impact)},` +
      suffix;
  });
  updated++;
});

fs.writeFileSync(file, s);
console.log('已为', updated, '个节点补充 4 段内容');
if (notFound.length) {
  console.log('\\n未找到（可能节点标题不完全匹配）:');
  notFound.forEach(t => console.log(' ', t));
}
