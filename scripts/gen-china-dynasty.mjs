const chinaDir = path.join(root, 'public/geo/china')

function writePoly(id, geom, extraProps = {}) {
  const fc = {
    type: 'FeatureCollection',
    features: [{
      type: 'Feature',
      properties: { name: id, source: 'hand-drawn approximate historical frontier (after 谭其骧《中国历史地图集》)', ...extraProps },
      geometry: geom,
    }],
  }
  fs.writeFileSync(path.join(chinaDir, `${id}.geojson`), JSON.stringify(fc))
}

for (const [id, ring] of Object.entries(CHINA)) {
  const r = ring[ring.length - 1]
  const closed = (r[0] === ring[0][0] && r[1] === ring[0][1]) ? ring : [...ring, ring[0]]
  writePoly(id, { type: 'Polygon', coordinates: [closed] })
  console.log(`china/${id}: ${closed.length} pts (Polygon)`)
}

// Qing as MultiPolygon
