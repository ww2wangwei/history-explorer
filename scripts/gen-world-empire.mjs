// 生成 8 个世界帝国的近似历史疆域 GeoJSON。
// 与中国朝代同理：现代国家 union 会过度包含/错误归并（如蒙古缺俄罗斯、英帝国把
// 整块国家塞进），且会把多块分离的疆域连成一团。这里改为按各帝国**鼎盛期的实际
// 历史边境**手绘多边形（MultiPolygon 拆分成当时实际控制的各块相连陆地）。
//
// 坐标为 (lon, lat)，东经/北纬正数。这是近似绘制（手画），参考谭其骧《中国历史
// 历史地图集》及各帝国权威历史地图，标注于 properties.source。
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const outDir = path.join(root, 'public/geo/world/eras')

function close(ring) {
  const r = ring[ring.length - 1]
  return (r[0] === ring[0][0] && r[1] === ring[0][1]) ? ring : [...ring, ring[0]]
}
function poly(rings) {
  return { type: 'Polygon', coordinates: rings.map(close) }
}
function multi(ringsList) {
  return { type: 'MultiPolygon', coordinates: ringsList.map(r => [close(r)]) }
}
function writeEmpire(id, geom) {
  const fc = {
    type: 'FeatureCollection',
    features: [{ type: 'Feature', properties: { name: id, source: 'hand-drawn approximate historical frontier' }, geometry: geom }],
  }
  fs.writeFileSync(path.join(outDir, `${id}.geojson`), JSON.stringify(fc))
}

