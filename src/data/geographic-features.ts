/**
 * 主要地理要素数据
 * 用于在地图上叠加显示 + 在"全地理"页弹出详情
 *
 * 所有坐标都是 [经度, 纬度]
 *
 * 图片来源：Bing 图片搜索 (tse1.mm.bing.net)
 * 后续可替换为维基共享资源或本地图片
 */

export type GeoFeatureType = 'continent' | 'sea' | 'mountain' | 'river' | 'desert' | 'region' | 'lake' | 'waterfall' | 'plain' | 'peninsula' | 'strait'

export interface GeoFeature {
  id: string
  type: GeoFeatureType
  name: string
  /** 标签显示位置 [经度, 纬度] */
  labelPos: [number, number]
  /** 几何要素（不同类型含义不同）：
   * - continent/sea: Polygon 轮廓
   * - mountain: 折线（简化山脊线）
   * - river: 折线（河流路径）
   * - region: 折线（区域）
   */
  geometry: [number, number][]
  /** 重要性 1-3，影响显示大小 */
  importance?: 1 | 2 | 3
  /** 中文介绍 */
  description?: string
  /** 图片 URL (Bing 图片搜索真实图片) */
  imageUrl?: string
  /** 图片来源标注 */
  imageCredit?: string
}

