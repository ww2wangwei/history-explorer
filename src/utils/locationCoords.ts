/**
 * 地名 → 经纬度（模糊匹配）
 * 优先精确匹配，否则尝试包含子串，最后回退到 China 中点
 */
export function lookupLocation(name: string): LngLat | null {
  if (!name) return null
  // 1. 精确
  if (DICT[name]) return DICT[name]
  // 2. 反向：找 DICT 中所有键包含 name 的
  for (const k of Object.keys(DICT)) {
    if (k.includes(name) || name.includes(k)) return DICT[k]
  }
  // 3. 回退：含"中国"→ 中国
  if (name.includes('中国') || name.includes('华北') || name.includes('华中') || name.includes('华东') || name.includes('华南') || name.includes('中原')) {
    return DICT['中国']
  }
  // 4. 整体回退：地球中点
  return [50.0, 30.0]
}

/**
 * 地名 → 经纬度（严格匹配，无兜底）
 * 仅精确匹配或包含匹配命中时返回坐标；否则返回 null。
 * 用于「📍 在地图上定位」按钮的可用性判定：查不到坐标就 disable 按钮，
 * 避免像 lookupLocation 那样把无法定位的地名错误落到地球中点。
 */
export function lookupLocationStrict(name: string): LngLat | null {
  if (!name) return null
  // 1. 精确
  if (DICT[name]) return DICT[name]
  // 2. 双向包含
  for (const k of Object.keys(DICT)) {
    if (k.includes(name) || name.includes(k)) return DICT[k]
  }
  return null
}
